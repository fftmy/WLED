//  4. Subscribe to input report notifications and map them to the paddle.
//
// Threading: NimBLE calls the scan/client/notify callbacks from its own
// FreeRTOS task, so the callbacks only store data (address, flags, the raw
// report bytes). All GATT operations, parsing and WLED state access happen
// in loop() context (see AGENTS.md "ESP32 Task Synchronization").
// ---------------------------------------------------------------------------
