// Bluetooth gamepad support: a small BLE HID host built on NimBLE-Arduino.
// Gated behind MYGAMES_BLUEPAD32 so environments without the library keep
// compiling unchanged.
//
// How it works:
//  1. Scan for advertising devices named "Xbox" or advertising the HID
//     gamepad appearance (0x03C4).
//  2. Connect, pair/bond (Just Works), then find the HID service (0x1812).
//  3. Read the Report Map characteristic (0x2A4B) and parse it to learn the
