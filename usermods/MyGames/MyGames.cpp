// one axis field inside the input report
struct GpAxisField {
  uint8_t usage;       // HID generic-desktop usage (0x30 = X, 0x31 = Y, ...)
  uint8_t sizeBits;    // field width in bits
  uint16_t offsetBits; // field position inside the input report (after the id)
  int32_t logMin;      // declared Logical Minimum
  int32_t logMax;      // declared Logical Maximum; zero point = (min+max+1)/2
};

// layout of the gamepad input report, extracted from the Report Map
struct GpHidLayout {
  bool valid;
  bool gamepadish;      // report belongs to a gamepad/joystick collection
  uint8_t reportId;     // 0 = device does not use report ids
  uint8_t btnOffsetBits;
  uint8_t btnBits;      // button bitmap size in bits (0 = none found)
  uint8_t btnUsageMin;  // HID button usage of bit 0 (1 = button "A" on Xbox)
  uint8_t hatOffsetBits;
  uint8_t hatSizeBits;  // 0 = no hat switch found
  int32_t hatLogMin;    // declared hat logical range (Xbox: 1..8, 0 = neutral)
  int32_t hatLogMax;
  GpAxisField axes[6];
  uint8_t axisCount;
  int8_t axisX;         // index of the left-stick X/Y axes in axes[]
  int8_t axisY;
};

static GpHidLayout gpLayout = {};

struct GpParseState {
  // global items
  uint8_t usagePage;
  uint8_t reportId;
  uint16_t reportSize;
  uint16_t reportCount;
  int32_t logMin;      // global Logical Minimum (signed, sign-extended)
  int32_t logMax;      // global Logical Maximum
  // global Push/Pop stack (rarely used, kept for correctness)
  struct { uint8_t usagePage; uint16_t reportSize; uint16_t reportCount; int32_t logMin; int32_t logMax; } stack[4];
  uint8_t stackDepth;
  // local items
  uint16_t usageList[8]; // explicit usages, page = current usagePage
  uint8_t usageCount;
  uint16_t usageMin;
  uint16_t usageMax;
  bool haveUsageRange;
  // collection path: colStack[d] = path up to depth d contains a gamepad-ish
  // (joystick/gamepad/multi-axis) collection
  bool colStack[8];
  uint8_t colDepth;
  // current input report candidate
  GpHidLayout cur;
  uint16_t curOffsetBits;
  bool curActive;
  // best candidate found so far
  GpHidLayout best;
  uint8_t bestScore;
};

// record an axis or hat-switch field for one usage of the generic desktop page
static void gpAddField(GpParseState* st, uint16_t usage, uint16_t offsetBits, uint16_t sizeBits)
{
  if (st->usagePage != 0x01) return; // generic desktop page only
  if (usage >= 0x30 && usage <= 0x38 && st->cur.axisCount < 6) {
    GpAxisField& f = st->cur.axes[st->cur.axisCount];
    f.usage = usage;
    f.sizeBits = sizeBits;
    f.offsetBits = offsetBits;
    f.logMin = st->logMin;
    f.logMax = st->logMax;
    // the left stick is the FIRST X/Y pair in declaration order; the Xbox map
    // labels it Rx/Ry (0x33/0x34) and its "X"/"Y" usages belong to the right
    // stick, so matching by usage id picks the wrong pair
    if (st->cur.axisX < 0) st->cur.axisX = st->cur.axisCount;
    else if (st->cur.axisY < 0) st->cur.axisY = st->cur.axisCount;
    st->cur.axisCount++;
  } else if (usage == 0x39) { // hat switch
    st->cur.hatOffsetBits = offsetBits;
    st->cur.hatSizeBits = sizeBits;
    st->cur.hatLogMin = st->logMin;
    st->cur.hatLogMax = st->logMax;
  }
}

// compare the finished candidate against the best one found so far
static void gpEvaluateCandidate(GpParseState* st)
{
  if (!st->curActive) return;
  uint8_t score = st->cur.axisCount;
  if (st->cur.gamepadish) score += 8;
  if (st->cur.btnBits) score += 2;
  if (st->cur.axisX >= 0 && st->cur.axisY >= 0 && st->cur.btnBits) score += 4;
  if (score > st->bestScore) {
    st->best = st->cur;
    st->bestScore = score;
  }
  st->curActive = false;
}

// parse the raw Report Map descriptor bytes and fill gpLayout
static void gpParseReportMap(const uint8_t* data, size_t len)
{
  GpParseState st = {};
  st.usagePage = 0x01; // default per HID spec

  size_t i = 0;
  while (i < len) {
    const uint8_t hdr = data[i++];
    if (hdr == 0xFE) { // long item: skip (not used by gamepads)
      if (i >= len) break;
      i += (size_t)data[i] + 1;
      continue;
    }
    const uint8_t tag = (hdr >> 4) & 0x0F;
    const uint8_t type = (hdr >> 2) & 0x03;  // 0=main 1=global 2=local
    const uint8_t szCode = hdr & 0x03;       // length code: 0, 1, 2 or 4 bytes
    const uint8_t szField = (szCode == 3) ? 4 : szCode; // code 3 means 4 bytes
    if (i + szField > len) break;
    uint32_t val = 0;
    for (uint8_t b = 0; b < szField; b++) val |= (uint32_t)data[i + b] << (8 * b);
    i += szField;

    if (type == 1) { // ---------------------------------------------------------------- global
      switch (tag) {
        case 0x00: st.usagePage = val & 0xFF; break;       // Usage Page
        case 0x07: st.reportSize = val; break;             // Report Size
        case 0x08: st.reportId = val & 0xFF; break;        // Report ID
        case 0x09: st.reportCount = val; break;            // Report Count
        case 0x01: // Logical Minimum (signed)
        case 0x02: { // Logical Maximum (signed)
          // sign-extend by field width, e.g. -1 in 8 bits = 0xFF
          int32_t sval = (int32_t)val;
          if (szField && szField < 4 && (val & (1u << (szField * 8 - 1))))
            sval = (int32_t)(val | (0xFFFFFFFFu << (szField * 8)));
          if (tag == 0x01) st.logMin = sval; else st.logMax = sval;
          break;
        }
        case 0x0A: // Push
          if (st.stackDepth < 4) {
            st.stack[st.stackDepth].usagePage = st.usagePage;
            st.stack[st.stackDepth].reportSize = st.reportSize;
            st.stack[st.stackDepth].reportCount = st.reportCount;
            st.stack[st.stackDepth].logMin = st.logMin;
            st.stack[st.stackDepth].logMax = st.logMax;
            st.stackDepth++;
          }
          break;
        case 0x0B: // Pop
          if (st.stackDepth) {
            st.stackDepth--;
            st.usagePage = st.stack[st.stackDepth].usagePage;
            st.reportSize = st.stack[st.stackDepth].reportSize;
            st.reportCount = st.stack[st.stackDepth].reportCount;
            st.logMin = st.stack[st.stackDepth].logMin;
            st.logMax = st.stack[st.stackDepth].logMax;
          }
          break;
        default: break; // Logical/Physical Min/Max, Unit: not needed here
      }
    } else if (type == 2) { // -------------------------------------------------------- local
      switch (tag) {
        case 0x00: if (st.usageCount < 8) st.usageList[st.usageCount++] = val; break; // Usage
        case 0x01: st.usageMin = val; st.haveUsageRange = true; break;                // Usage Minimum
        case 0x02: st.usageMax = val; break;                                          // Usage Maximum
        default: break; // designators/delimiters: not needed here
      }
    } else if (type == 0) { // -------------------------------------------------------- main
      switch (tag) {
        case 0x0A: { // Collection
          bool gp = false;
          if (st.usagePage == 0x01) {
            const uint16_t cu = st.usageCount ? st.usageList[0] : (st.haveUsageRange ? st.usageMin : 0);
            if (cu == 0x04 || cu == 0x05 || cu == 0x08) gp = true; // joystick / gamepad / multi-axis
          }
          if (st.colDepth < 8) {
            st.colStack[st.colDepth] = gp || (st.colDepth ? st.colStack[st.colDepth - 1] : false);
            st.colDepth++;
          }
          // HID spec: ANY main item resets the local item state. Collections
          // must clear it too - the Xbox map tags each stick pair with a
          // "Pointer" usage inside a nested collection, and those stale
          // usages would otherwise shift every following field by one slot.
          st.usageCount = 0;
          st.haveUsageRange = false;
          st.usageMin = st.usageMax = 0;
          break;
        }
        case 0x0C: // End Collection
          if (st.colDepth) st.colDepth--;
          st.usageCount = 0;
          st.haveUsageRange = false;
          st.usageMin = st.usageMax = 0;
          break;
        case 0x08: { // Input
          const bool isData = !(val & 0x01); // bit0: Data(0)/Const(1)
          const bool isVar = val & 0x02;     // bit1: Array(0)/Var(1)
          const uint16_t bits = st.reportSize * st.reportCount;

          // a different (or first) report id starts a new candidate layout
          if (!st.curActive || st.reportId != st.cur.reportId) {
            gpEvaluateCandidate(&st);
            st.cur = GpHidLayout {};
            st.cur.reportId = st.reportId;
            // GpHidLayout{} zero-initializes these, but 0 is a VALID axis
            // index - mark "unset" explicitly or they never get assigned and
            // X and Y both read axes[0]
            st.cur.axisX = -1;
            st.cur.axisY = -1;
            st.curOffsetBits = 0;
            st.curActive = true;
          }
          if (st.colDepth && st.colStack[st.colDepth - 1]) st.cur.gamepadish = true;

          if (isData && isVar && st.curActive) {
            if (st.usagePage == 0x09 && st.haveUsageRange && !st.cur.btnBits) {
              // button bitmap: bit i = usage (usageMin + i)
              st.cur.btnOffsetBits = st.curOffsetBits;
              st.cur.btnBits = (bits > 255) ? 255 : bits;
              st.cur.btnUsageMin = st.usageMin;
            } else {
              // axes / hat: one usage per field
              if (st.haveUsageRange) {
                // cap the loop: a malformed range must not spin 65536 times
                for (uint16_t u = st.usageMin; u <= st.usageMax && u - st.usageMin < 32; u++)
                  gpAddField(&st, u, st.curOffsetBits + (u - st.usageMin) * st.reportSize, st.reportSize);
              } else {
                for (uint8_t k = 0; k < st.usageCount; k++)
                  gpAddField(&st, st.usageList[k], st.curOffsetBits + k * st.reportSize, st.reportSize);
              }
            }
          }
          st.curOffsetBits += bits;
          // input items clear the local item state
          st.usageCount = 0;
          st.haveUsageRange = false;
          st.usageMin = st.usageMax = 0;
          break;
        }
        case 0x09: // Output
        case 0x0B: // Feature
          // not collected, but they clear local item state
          st.usageCount = 0;
          st.haveUsageRange = false;
          st.usageMin = st.usageMax = 0;
          break;
        default: break;
      }
    }
  }
  gpEvaluateCandidate(&st);

  // a usable gamepad report needs at least the two stick axes
  gpLayout = st.best;
  gpLayout.valid = (st.bestScore > 0) && (st.best.axisX >= 0) && (st.best.axisY >= 0);
  // hats without a declared logical range: standard HID hat uses 0..7
  if (gpLayout.hatSizeBits && gpLayout.hatLogMax <= gpLayout.hatLogMin) {
    gpLayout.hatLogMin = 0;
    gpLayout.hatLogMax = 7;
  }

  DEBUG_PRINTF_P(PSTR("MyGames: HID map parsed: reportId=%u btn=%u bits@%u hat=%u bits@%u range=%d..%d axes=%u valid=%u\n"),
    gpLayout.reportId, gpLayout.btnBits, gpLayout.btnOffsetBits, gpLayout.hatSizeBits,
    gpLayout.hatOffsetBits, (int)gpLayout.hatLogMin, (int)gpLayout.hatLogMax,
    gpLayout.axisCount, gpLayout.valid);
  for (uint8_t k = 0; k < gpLayout.axisCount; k++) {
    const GpAxisField& f = gpLayout.axes[k];
    DEBUG_PRINTF_P(PSTR("MyGames:  axis %u: usage 0x%02x bits@%u size=%u range=%d..%d%s%s\n"),
      k, f.usage, f.offsetBits, f.sizeBits, (int)f.logMin, (int)f.logMax,
      (k == gpLayout.axisX) ? " [X]" : "", (k == gpLayout.axisY) ? " [Y]" : "");
  }
}

// extract up to 32 bits (HID bit order: LSB first) from a report buffer
static uint32_t gpGetBits(const uint8_t* rep, uint16_t offsetBits, uint8_t sizeBits)
{
  uint32_t v = 0;
  for (uint8_t b = 0; b < sizeBits && b < 32; b++) {
    const uint16_t bit = offsetBits + b;
    v |= (uint32_t)((rep[bit >> 3] >> (bit & 7)) & 1) << b;
  }
  return v;
}

// convert one axis field to a ±32768-range signed value, re-centered on the
// declared logical range (gamepad sticks are usually unsigned 0..65535 with
// the zero point at 32768; treating them as signed yields near-zero readings)
static int32_t gpAxisValue(const uint8_t* rep, const GpAxisField& f)
{
  if (f.sizeBits < 2 || f.sizeBits > 16) return 0; // unsupported field width
  const uint32_t v = gpGetBits(rep, f.offsetBits, f.sizeBits);
  // signed axis (e.g. Logical Min < 0): interpret the raw bits as signed
  if (f.logMin < 0 && f.logMax >= 0) {
    const int32_t half = 1 << (f.sizeBits - 1);
    return (v < (uint32_t)half) ? (int32_t)v : (int32_t)v - (1 << f.sizeBits);
  }
  // unsigned axis: zero point at the middle of the declared range
  int32_t center;
  if (f.logMax > f.logMin) center = (f.logMin + f.logMax + 1) / 2;
  else center = 1 << (f.sizeBits - 1); // no usable range: assume unsigned
  // scale to ±32768 so the deadzone thresholds stay independent of field width
  int32_t diff = (int32_t)v - center;
  if (f.sizeBits && f.sizeBits < 16) diff *= (1 << (16 - f.sizeBits));
  return diff;
}

