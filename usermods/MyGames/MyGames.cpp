// latest HID notification; written from the NimBLE task, consumed by loop()
static uint8_t gpReport[32];
static volatile size_t gpReportLen = 0;
static bool gpNoReportId = false;   // device sends input reports WITHOUT the id byte
static uint8_t gpIdMismatch = 0;    // consecutive notifications with unexpected id byte

static NimBLEClient* gpClient = nullptr;
static NimBLEAddress gpTargetAddr;
static volatile bool gpTargetFound = false;
static volatile bool gpClientLost = false;
static volatile bool gpAuthDone = false;      // pairing/bonding finished (NimBLE task)
static volatile bool gpHidConfigured = false; // report map parsed and subscribed
static unsigned long gpRescanAt = 0;
static unsigned long gpConnectAt = 0;         // millis() when connect succeeded

static void gpNotifyCb(NimBLERemoteCharacteristic* c, uint8_t* data, size_t len, bool isNotify)
{
  // NimBLE task context: only copy the report, never touch WLED state
  if (len <= sizeof(gpReport)) {
    memcpy(gpReport, data, len);
    gpReportLen = len;
  }
}

// scan-complete callback; the continuous scan only stops on error/host reset,
// restarts are handled in gpTask()
static void gpScanCompleteCb(NimBLEScanResults results) {}

class GpScanCallbacks : public NimBLEAdvertisedDeviceCallbacks {
  void onResult(NimBLEAdvertisedDevice* dev) override {
    if (gpTargetFound || gpClient) return;
    bool match = false;
    if (dev->haveName() && dev->getName().find("Xbox") != std::string::npos) match = true;
    if (!match && dev->haveAppearance() && dev->getAppearance() == 0x03C4) match = true; // HID gamepad
    if (match) {
      gpTargetAddr = dev->getAddress();
      gpTargetFound = true;
      DEBUG_PRINTLN(F("MyGames: BLE gamepad found."));
    }
  }
};
static GpScanCallbacks gpScanCallbacks;

class GpClientCallbacks : public NimBLEClientCallbacks {
  void onDisconnect(NimBLEClient* c) override { gpClientLost = true; }
  uint32_t onPassKeyRequest() override { return 0; }
  bool onConfirmPIN(uint32_t pin) override { return true; } // Just Works pairing
  // security procedure finished (success or failure). Strict devices like the
  // Xbox controller only allow encrypted GATT reads of their HID report map
  // once this has fired; permissive devices are handled by a 3 s timeout.
  void onAuthenticationComplete(ble_gap_conn_desc* desc) override { gpAuthDone = true; }
};
static GpClientCallbacks gpClientCallbacks;

// connect to the found gamepad and start pairing/bonding. Pairing is
// asynchronous: the HID configuration runs from gpTask() once
// onAuthenticationComplete has fired, or after a 3 s timeout for gamepads
// that do not require security.
static void gpConnectAndConfigure()
{
  NimBLEScan* scan = NimBLEDevice::getScan();
  scan->stop();
  scan->clearResults();

  gpClient = NimBLEDevice::createClient();
  gpClient->setClientCallbacks(&gpClientCallbacks, false);
  gpClient->setConnectionParams(12, 24, 0, 200); // 15-30ms interval, 2s supervision timeout
  if (!gpClient->connect(gpTargetAddr)) {
    DEBUG_PRINTLN(F("MyGames: gamepad connect failed."));
    NimBLEDevice::deleteClient(gpClient);
    gpClient = nullptr;
    gpRescanAt = millis() + 2000;
    return;
  }
  DEBUG_PRINTLN(F("MyGames: gamepad connected, waiting for pairing..."));
  gpAuthDone = false;
  gpHidConfigured = false;
  // framing is a per-device property: re-detect for the newly connected pad
  gpNoReportId = false;
  gpIdMismatch = 0;
  gpConnectAt = millis();
  NimBLEDevice::startSecurity(gpClient->getConnId()); // trigger pairing/bonding
}

// read/parse the report map and subscribe to input notifications.
// Blocks the main loop for a moment, once per connection.
static void gpConfigureHid()
{
  NimBLERemoteService* svc = gpClient->getService(NimBLEUUID((uint16_t)0x1812)); // HID service
  if (!svc) {
    DEBUG_PRINTLN(F("MyGames: no HID service, not a gamepad."));
    gpClientLost = true; // reuse the disconnect path for cleanup and rescan
    return;
  }

  // report map -> input report layout
  NimBLERemoteCharacteristic* mapChar = svc->getCharacteristic(NimBLEUUID((uint16_t)0x2A4B));
  if (mapChar && mapChar->canRead()) {
    const std::string map = mapChar->readValue();
#ifdef WLED_DEBUG
    // --- full report map dump (debug builds only): 16 bytes/line with offset ---
    DEBUG_PRINTF_P(PSTR("MyGames: report map %u bytes:\n"), (unsigned)map.size());
    for (size_t off = 0; off < map.size(); off += 16) {
      DEBUG_PRINTF_P(PSTR("MyGames:  %03x:"), (unsigned)off);
      char line[49]; // 16 * " %02x" + NUL
      size_t n = 0;
      for (size_t k = off; k < map.size() && k < off + 16; k++)
        n += snprintf(line + n, sizeof(line) - n, " %02x", (unsigned)(uint8_t)map[k]);
      DEBUG_PRINTF_P(PSTR("%s\n"), line);
    }
#endif
    gpLayout = GpHidLayout(); // reset, so a failed read never leaves a stale layout
    gpParseReportMap((const uint8_t*)map.data(), map.size());
  } else {
    DEBUG_PRINTLN(F("MyGames: report map not readable."));
  }
  if (!gpLayout.valid) {
    DEBUG_PRINTLN(F("MyGames: no usable gamepad report in HID map."));
    gpClientLost = true;
    return;
  }

  // subscribe to every input report characteristic that matches the layout
  std::vector<NimBLERemoteCharacteristic*>* chars = svc->getCharacteristics(true);
  if (!chars) {
    DEBUG_PRINTLN(F("MyGames: HID characteristic discovery failed."));
    gpClientLost = true;
    return;
  }
  for (NimBLERemoteCharacteristic* ch : *chars) {
    if (!ch->canNotify()) continue;
    uint8_t reportId = gpLayout.reportId;
    NimBLERemoteDescriptor* d = ch->getDescriptor(NimBLEUUID((uint16_t)0x2908)); // Report Reference
    if (d) {
      const std::string v = d->readValue(); // [report id, report type]
      if (v.size() >= 2 && v[1] == 1) reportId = v[0]; // 1 = input report
      else continue; // output/feature report, ignore
    }
    if (reportId != gpLayout.reportId) continue;
    if (ch->subscribe(true, gpNotifyCb)) DEBUG_PRINTLN(F("MyGames: subscribed to input reports."));
  }
  gpHidConfigured = true;
}

// one-shot flag for the deferred BLE bring-up (see gpTask())
static bool gpStarted = false;
static void gpStart(); // defined below (NimBLE initialization)

// periodic state machine, called from loop()
static void gpTask()
{
  if (!gpStarted) {
    // Deferred BLE bring-up: WLED performs flash writes during and shortly
    // after boot (WiFi credentials to NVS via WiFi.persistent(true), possible
    // cfg.json creation). On ESP32-C3 a flash write/erase while the BLE
    // controller is running aborts in spi_flash (the BLE interrupt cannot be
    // fully masked during the cache-disabled window of the flash operation),
    // which boot-loops the board. Start scanning only once the network is up
    // (all boot-time flash writes done), or well past boot in AP mode.
    if (millis() < 10000) return;
    if (!Network.isConnected() && millis() < 45000) return;
    gpStart();
    gpStarted = true;
  }
  if (gpClientLost) {
    gpClientLost = false;
    DEBUG_PRINTLN(F("MyGames: gamepad disconnected, rescanning."));
    if (gpClient) {
      NimBLEDevice::deleteClient(gpClient);
      gpClient = nullptr;
    }
    gpRescanAt = millis() + 3000;
  }
  // wait for pairing, then configure HID. Strict devices (Xbox) only allow
  // encrypted GATT reads once the security procedure is complete; gamepads
  // that skip security are covered by the 3 s timeout.
  if (gpClient && !gpHidConfigured) {
    if (gpAuthDone || millis() - gpConnectAt > 3000) gpConfigureHid();
    return;
  }
  if (!gpClient) {
    if (gpTargetFound) {
      gpTargetFound = false;
      gpConnectAndConfigure();
      return;
    }
    // scanning runs until stopped; restart it after the pause expires.
    // results are cleared so a device seen before triggers onResult again
    if (millis() >= gpRescanAt) {
      NimBLEScan* scan = NimBLEDevice::getScan();
      if (!scan->isScanning()) {
        scan->clearResults();
        scan->clearDuplicateCache();
        scan->start(0, gpScanCompleteCb, false);
      }
    }
  }
}

// consume the latest input report and translate it to game controls:
//   left stick up/down, or D-pad up/down: move the paddle
// latest gamepad input state. BLE HID controllers only transmit when a value
// CHANGES (battery saving), so the report handler just stores the values and
// the game integrates them every main-loop iteration - doing the movement
// math per report stalled the paddle until the next stick movement arrived.
static std::atomic<int32_t> gpStickY { 0 };         // left stick Y, deadzoned, +/-32768
static std::atomic<uint32_t> gpHat { 0xFFFFFFFFu }; // raw hat value, 0xFFFFFFFF = neutral
static std::atomic<uint32_t> gpButtons { 0 };       // button bitmap, bit 0 = A (usage 1)

static void gpConsumeInput()
{
  // --- 1) pull the newest report into the persistent input state ---
  const size_t len = gpReportLen;
  if (len) {
    gpReportLen = 0; // consume
    // Some gamepads (this Xbox does) send the input report WITHOUT the
    // report id byte although the map declares one - byte 0 is then already
    // stick data (the low byte of LX). Detect several consecutive
    // notifications whose first byte is not the expected id and latch to
    // id-less framing (kept for the rest of the connection).
    const uint8_t* rep = gpReport;
    bool fresh = true;
    if (gpLayout.reportId && !gpNoReportId) {
      if (len >= 2 && gpReport[0] == gpLayout.reportId) {
        gpIdMismatch = 0;
        rep++;
      } else {
        fresh = false;
        if (++gpIdMismatch >= 4) {
          gpNoReportId = true;
          DEBUG_PRINTLN(F("MyGames: reports carry no report id byte, adjusting."));
        }
      }
    }
#ifdef WLED_DEBUG
    // --- raw report dump (debug builds only). Rate-limited to 5 lines/s for
    // stick-only reports, but any change in the buttons/hat bytes or an
    // unexpected report id prints IMMEDIATELY, so rare inputs (e.g. D-pad)
    // cannot vanish between rate-limit windows.
    static unsigned long lastDump = 0;
    static uint32_t lastAuxLo = 0, lastAuxHi = 0;
    const uint32_t auxLo = (len >= 12) ? (uint32_t)gpReport[8] | ((uint32_t)gpReport[9] << 8)
      | ((uint32_t)gpReport[10] << 16) | ((uint32_t)gpReport[11] << 24) : 0;
    const uint32_t auxHi = (len >= 16) ? (uint32_t)gpReport[12] | ((uint32_t)gpReport[13] << 8)
      | ((uint32_t)gpReport[14] << 16) | ((uint32_t)gpReport[15] << 24) : 0;
    const unsigned long tNow = millis();
    if (tNow - lastDump >= 200 || !fresh || auxLo != lastAuxLo || auxHi != lastAuxHi) {
      lastDump = tNow;
      lastAuxLo = auxLo;
      lastAuxHi = auxHi;
      DEBUG_PRINTF_P(PSTR("MyGames: report[%u]:"), (unsigned)len);
      for (size_t k = 0; k < len; k++) DEBUG_PRINTF_P(PSTR(" %02x"), gpReport[k]);
      if (gpLayout.valid && fresh) {
        const int32_t dax = (gpLayout.axisX >= 0) ? gpAxisValue(rep, gpLayout.axes[gpLayout.axisX]) : 0;
        const int32_t day = (gpLayout.axisY >= 0) ? gpAxisValue(rep, gpLayout.axes[gpLayout.axisY]) : 0;
        const uint32_t dbtn = gpLayout.btnBits ? gpGetBits(rep, gpLayout.btnOffsetBits, gpLayout.btnBits) : 0;
        const uint32_t dhat = gpLayout.hatSizeBits ? gpGetBits(rep, gpLayout.hatOffsetBits, gpLayout.hatSizeBits) : 0xF;
        DEBUG_PRINTF_P(PSTR("  |  X=%d Y=%d btn=0x%x hat=%u off=%d\n"),
          dax, day, (unsigned)dbtn, (unsigned)dhat, (int)gpPaddleOff.load());
      } else {
        DEBUG_PRINTF_P(PSTR("  |  (report id 0x%02x, expected 0x%02x)\n"),
          (unsigned)gpReport[0], (unsigned)gpLayout.reportId);
      }
    }
#endif
    if (gpLayout.valid && fresh) {
      if (gpLayout.axisY >= 0) {
        int32_t ay = gpAxisValue(rep, gpLayout.axes[gpLayout.axisY]);
        if (ay > -2000 && ay < 2000) ay = 0; // deadzone (~6% of full scale)
        gpStickY = ay;
      }
      if (gpLayout.hatSizeBits)
        gpHat = gpGetBits(rep, gpLayout.hatOffsetBits, gpLayout.hatSizeBits);
      if (gpLayout.btnBits)
        gpButtons = gpGetBits(rep, gpLayout.btnOffsetBits, gpLayout.btnBits);
    }
  }

  // --- 2) apply the held input state, every main-loop iteration ---
  // input reaches the game only while its effect is actually shown
  if (strip.getMainSegment().mode != modePongId) return;

  const unsigned long now = millis();
  static unsigned long lastMove = 0;
  static unsigned long lastHatStep = 0;
  static int32_t accPy = 0; // sub-pixel paddle accumulator
  const unsigned long dtMs = now - lastMove;
  lastMove = now;

  // left stick Y: velocity integration over the loop period; full deflection
  // moves the paddle at a fixed 200 px/s (the effect's Speed slider controls
  // the ball speed instead, so both paddles stay on equal terms)
  if (dtMs && dtMs < 200) { // skip huge gaps (e.g. during FS activity)
    // counts*ms needed for one pixel at full deflection = 32768 * 1000 / 200
    constexpr int32_t denom = 163840;
    accPy += gpStickY.load() * (int32_t)dtMs;
    gpPaddleOff += accPy / denom;
    accPy %= denom;
  }

  // hat switch (D-pad): one step on press, then auto-repeat every 120 ms while
  // held; neutral = any value outside the declared logical range (Xbox uses
  // 1..8 with 0 = neutral)
  const int32_t hat = (int32_t)gpHat.load();
  if (gpLayout.hatSizeBits && hat >= gpLayout.hatLogMin && hat <= gpLayout.hatLogMax) {
    static const int8_t dy[8] = { -1, -1, 0, 1, 1, 1, 0, -1 }; // N NE E SE S SW W NW
    if (now - lastHatStep > 120) {
      gpPaddleOff += dy[hat - gpLayout.hatLogMin];
      lastHatStep = now;
    }
  } else {
    lastHatStep = 0; // arm, so the next press steps immediately
  }
}

// one-time initialization, called once from gpTask() after boot has finished
static void gpStart()
{
  // Pre-flight NVS health check: NimBLEDevice::init() aborts the whole board
  // via ESP_ERROR_CHECK(nvs_flash_erase()) when the NVS partition reports no
  // free pages (e.g. after a power loss / crash during an earlier flash
  // write). Do the check and recovery here instead, where a failure is
  // handled gracefully, no BT controller exists yet and WLED keeps running
  // without the gamepad rather than rebooting.
  esp_err_t nvsErr = nvs_flash_init();
  if (nvsErr == ESP_ERR_NVS_NO_FREE_PAGES || nvsErr == ESP_ERR_NVS_NEW_VERSION_FOUND) {
    DEBUG_PRINTLN(F("MyGames: NVS needs recovery, erasing..."));
    nvsErr = nvs_flash_erase();
    if (nvsErr == ESP_OK) nvsErr = nvs_flash_init();
  }
  if (nvsErr != ESP_OK) {
    DEBUG_PRINTF_P(PSTR("MyGames: NVS unusable (%d), BLE disabled.\n"), nvsErr);
    return;
  }

  // WiFi/BT coexistence policy (ESP32-C3/S3): the coexist core aborts in
  // coex_core_enable() at the second coex enable (our esp_bt_controller_enable
  // after WiFi is already up) when WiFi modem sleep is disabled:
  // "Error! Should enable WiFi modem sleep when both WiFi and Bluetooth are
  // enabled!!!" WLED defaults to noWifiSleep = true (WiFi.setSleep(false),
  // wled.cpp), so modem sleep must be forced back on before the BT controller
  // starts. Keep it on while the gamepad runs - slightly higher WiFi latency
  // and power draw is the price of WiFi+BLE coexistence on these chips.
  WiFi.setSleep(true);
  DEBUG_PRINTLN(F("MyGames: WiFi modem sleep enabled for coexistence"));

  DEBUG_PRINTF_P(PSTR("MyGames: starting BLE init, free heap %u\n"), ESP.getFreeHeap());
  NimBLEDevice::init("WLED-MyGames");
  DEBUG_PRINTF_P(PSTR("MyGames: BLE host synced, free heap %u\n"), ESP.getFreeHeap());
  NimBLEDevice::setSecurityAuth(true, false, true); // bonding, no MITM (Just Works), LE secure connections
  NimBLEDevice::setSecurityIOCap(BLE_HS_IO_NO_INPUT_OUTPUT);

  NimBLEScan* scan = NimBLEDevice::getScan();
  scan->setAdvertisedDeviceCallbacks(&gpScanCallbacks, false);
  scan->setActiveScan(true);
  scan->setInterval(97); // ~60/30ms interval/window: keeps radio time for WiFi
  scan->setWindow(48);
  scan->start(0, gpScanCompleteCb, false); // continuous scan until something is found

  // NOTE: pairing keys are stored in NVS, so the gamepad reconnects
  // automatically after a reboot. Uncomment to pair from scratch:
  // NimBLEDevice::deleteAllBonds();
}

